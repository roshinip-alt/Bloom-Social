package com.bloom.user;

import com.bloom.config.BloomProperties;
import com.bloom.goals.GoalProgressService;
import com.bloom.social.account.DemoAccountFactory;
import com.bloom.social.domain.ConnectedSocialAccount;
import com.bloom.social.domain.ConnectedSocialAccountRepository;
import com.bloom.social.domain.ConnectionStatus;
import com.bloom.social.domain.Provider;
import com.bloom.social.domain.SyncJob;
import com.bloom.social.sync.SyncService;
import java.time.Duration;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.UUID;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.context.event.ApplicationReadyEvent;
import org.springframework.context.event.EventListener;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

/**
 * Creates the two local workspaces on first start:
 * <ul>
 *   <li><b>Demo workspace</b> — clearly synthetic accounts (DEMO data mode), metrics generated by the demo sync
 *   source, and sample planning content from {@code database/seeds/R__demo_content.sql}. Resettable.</li>
 *   <li><b>My workspace</b> — empty; this is where live provider accounts are connected.</li>
 * </ul>
 */
@Component
public class DemoWorkspaceSeeder {
    /** Fixed so the UI's stored workspace selection survives a demo reset. */
    public static final UUID DEMO_WORKSPACE_ID = UUID.fromString("0b100000-0000-4000-8000-000000000001");
    public static final UUID PERSONAL_WORKSPACE_ID = UUID.fromString("0b100000-0000-4000-8000-000000000002");
    private static final Logger log = LoggerFactory.getLogger(DemoWorkspaceSeeder.class);

    private final WorkspaceRepository workspaces;
    private final ConnectedSocialAccountRepository accounts;
    private final DemoAccountFactory demoAccounts;
    private final SyncService sync;
    private final GoalProgressService goalProgress;
    private final JdbcTemplate jdbc;
    private final TransactionTemplate tx;
    private final BloomProperties props;

    public DemoWorkspaceSeeder(WorkspaceRepository workspaces, ConnectedSocialAccountRepository accounts,
                               DemoAccountFactory demoAccounts, SyncService sync, GoalProgressService goalProgress,
                               JdbcTemplate jdbc, PlatformTransactionManager txm, BloomProperties props) {
        this.workspaces = workspaces;
        this.accounts = accounts;
        this.demoAccounts = demoAccounts;
        this.sync = sync;
        this.goalProgress = goalProgress;
        this.jdbc = jdbc;
        this.tx = new TransactionTemplate(txm);
        this.props = props;
    }

    @EventListener(ApplicationReadyEvent.class)
    public void ensureWorkspaces() {
        if (props.workspace().seedDemoOnEmpty() && workspaces.findFirstByDemoTrue().isEmpty()) {
            seedDemoWorkspace();
        }
        if (!workspaces.existsByDemoFalse()) {
            workspaces.save(new Workspace(PERSONAL_WORKSPACE_ID, "My workspace", "UTC", "USD", false));
            log.info("Created the personal workspace for live connections");
        }
    }

    public Workspace resetDemoWorkspace() {
        tx.executeWithoutResult(s -> workspaces.findFirstByDemoTrue().ifPresent(w -> {
            workspaces.delete(w);
            workspaces.flush();
        }));
        return seedDemoWorkspace();
    }

    private Workspace seedDemoWorkspace() {
        Workspace ws = workspaces.save(
                new Workspace(DEMO_WORKSPACE_ID, "Demo workspace", "Europe/London", "USD", true));
        ConnectedSocialAccount instagram = demoAccounts.create(ws.getId(), Provider.INSTAGRAM, "fernandfield.demo", "Fern & Field (demo)");
        ConnectedSocialAccount youtube = demoAccounts.create(ws.getId(), Provider.YOUTUBE, "fernandfieldstudio.demo", "Fern & Field Studio (demo)");
        ConnectedSocialAccount tiktok = demoAccounts.create(ws.getId(), Provider.TIKTOK, "fernfield.demo", "Fern & Field (demo)");
        ConnectedSocialAccount kitchen = demoAccounts.create(ws.getId(), Provider.INSTAGRAM, "fernfield.kitchen.demo", "Fern Kitchen (demo)");
        for (ConnectedSocialAccount a : new ConnectedSocialAccount[]{instagram, youtube, tiktok, kitchen}) {
            sync.syncNow(a.getId(), SyncJob.Trigger.CONNECT);
        }
        // Demo scenario for the reconnect UI: one account whose (simulated) token was rejected.
        tx.executeWithoutResult(s -> accounts.findById(kitchen.getId()).ifPresent(a -> {
            Instant lastGood = Instant.now().minus(Duration.ofDays(9));
            jdbc.update("DELETE FROM analytics_snapshot WHERE account_id = ? AND snapshot_date > ?",
                    a.getId(), java.sql.Date.valueOf(LocalDate.ofInstant(lastGood, ZoneOffset.UTC)));
            a.setLastSuccessfulSyncAt(lastGood);
            a.setConnectionStatus(ConnectionStatus.EXPIRED);
            a.setLastSyncError("Demo scenario: this shows how Bloom handles a token the provider rejected (invalid_grant). "
                    + "A live account would be reconnected; in the demo, reset demo data in Settings to restore it.");
        }));
        jdbc.queryForObject("SELECT bloom_seed_demo_content(?)", Integer.class, ws.getId());
        goalProgress.refreshAnalyticsGoals(ws.getId());
        log.info("Seeded the demo workspace (synthetic data)");
        return ws;
    }
}
